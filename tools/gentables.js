// Extracts the name syllable tables and Hershey glyphs from the original
// fishdraw.js into a C++ include, so they are copied rather than retyped.
//
//   node tools/gentables.js path/to/fishdraw.js lib/fishdraw/fishdraw_tables.inc
const fs = require('fs');
const BS = String.fromCharCode(92);
const src = fs.readFileSync(process.argv[2], 'utf8');
const m = src.match(/let data =(\[\[[^]*?\]\])\s*let freq =(\[\[[^]*?\]\])/);
const data = JSON.parse(m[1]);
const freq = JSON.parse(m[2]);
const h = src.match(/let hershey_raw = (\{[^]*?\n\});/);
const hershey = eval('(' + h[1] + ')');
const esc = (s) => '"' + s.split(BS).join(BS + BS).split('"').join(BS + '"') + '"';

let o = '// Generated by tools/gentables.js from fishdraw.js (c) 2021 Lingdong Huang, MIT License.\n';
o += '// Do not edit by hand.\n\n';
for (let k = 0; k < 6; k++) {
  if (data[k].length != freq[k].length) throw new Error('table length mismatch');
  o += `static const char* const BINOMEN_${k}[] = {${data[k].map(esc).join(',')}};\n`;
  o += `static const uint8_t BINOMEN_FREQ_${k}[] = {${freq[k].join(',')}};\n`;
}
o += `static const uint8_t BINOMEN_COUNT[6] = {${data.map((d) => d.length).join(',')}};\n\n`;
const up = [];
const lo = [];
for (let i = 0; i < 26; i++) {
  up.push(esc(hershey[501 + i]));
  lo.push(esc(hershey[601 + i]));
}
o += `static const char* const HERSHEY_UPPER[26] = {\n  ${up.join(',\n  ')}\n};\n`;
o += `static const char* const HERSHEY_LOWER[26] = {\n  ${lo.join(',\n  ')}\n};\n`;
o += `static const char* const HERSHEY_DOT = ${esc(hershey[710])};\n`;
fs.writeFileSync(process.argv[3], o);
console.log('wrote', process.argv[3], data.map((d) => d.length).join(','));
